"""Export the probe-count Pareto dataset from eval run results.

Aggregates per-leg metrics (pass, iterations, raw/cache-adjusted tokens, DB
query counts, per-question probe lists) into one JSON file for downstream
visualization — the blog's datasets are generated by:

    python export_pareto_data.py -o ".../blog/pit_of_success_pareto_data.json"
    python export_pareto_data.py --cohort luna -o ".../blog/pit_of_success_pareto_data_luna.json"

One file per MODEL (see COHORTS). Token counts and probe habits are model
properties, so a mixed file would read as one experiment and invite cross-model
subtraction the numbers cannot support.

Legs are declared per cohort below — extend them as new cells land (regime and
warehouse_tables are experiment metadata that cannot be derived from the run
artifacts). Legs whose run directory has no report.json (externally stopped
runs) are computed from their agent_log JSONL files instead; their pass count
comes from the registry (scored out-of-band) or is null.

DB-query definitions (see handoff_noise_crossover.md §"Probe-count Pareto"):
SQL legs count run_query + run_file; enriched legs count `trilogy run` plus
`trilogy file write --run/--run-and-delete` (explore/agent-info/file read the
semantic model, not the database).
"""

