SQL_DB_TOOLS = ("run_query", "run_file")


def adjusted(prompt: int, cached: int, completion: int) -> float:
    """Cache-adjusted tokens: hits weighted at 0.1 per DeepSeek's ratio."""
    return (prompt - cached) + 0.1 * cached + completion


def _is_tri_db_call(arguments: dict) -> bool:
    args = arguments.get("args", [])
    if not args:
        return False
    return args[0] == "run" or (
        args[0] == "file"
        and len(args) > 1
        and args[1] == "write"
        and ("--run" in args or "--run-and-delete" in args)
    )


def leg_from_report(leg: Leg, results_dir: Path) -> dict:
    rep = json.loads(
        (results_dir / leg.run_dir / "report.json").read_text(encoding="utf-8")
    )
    agent = rep["agent"]
    pq = rep["per_query_metrics"]
    tc = agent.get("tool_calls_by_name", {})
    if leg.kind == "sql":
        db = sum(tc.get(t, 0) for t in SQL_DB_TOOLS)
        per_q_db = [
            sum(q["tool_calls_by_name"].get(t, 0) for t in SQL_DB_TOOLS) for q in pq
        ]
    else:
        # Subcommand counters can't see --run flags on `file write`; report-side
        # runs predate the one-call idiom, where `run` alone is exact.
        db = agent.get("trilogy_subcommands", {}).get("run", 0)
        per_q_db = [q.get("trilogy_subcommands", {}).get("run", 0) for q in pq]
    prompt = sum(q["prompt_tokens"] for q in pq)
    cached = sum(q.get("cached_prompt_tokens", 0) for q in pq)
    completion = sum(q["completion_tokens"] for q in pq)
    return _record(
        leg,
        questions=len(pq),
        pass_count=rep["summary"]["pass_count"],
        iterations=agent["iterations"],
        raw=sum(q["total_tokens"] for q in pq),
        prompt=prompt,
        cached=cached,
        completion=completion,
        db=db,
        per_q_db=per_q_db,
    )


def leg_from_jsonl(leg: Leg, results_dir: Path) -> dict:
    files = sorted(glob.glob(str(results_dir / leg.run_dir / "agent_log.q*.jsonl")))
    raw = cached = prompt = completion = iterations = 0
    per_q_db: list[int] = []
    for f in files:
        q_db = 0
        with open(f, encoding="utf-8") as handle:
            for line in handle:
                rec = json.loads(line)
                kind = rec.get("type")
                if kind == "llm_response":
                    iterations += 1
                    usage = rec.get("usage") or {}
                    raw += usage.get("total_tokens", 0)
                    cached += usage.get("cached_prompt_tokens", 0) or 0
                    prompt += usage.get("prompt_tokens", 0)
                    completion += usage.get("completion_tokens", 0)
                elif kind == "tool_call":
                    if leg.kind == "sql":
                        q_db += rec["name"] in SQL_DB_TOOLS
                    elif rec["name"] == "trilogy":
                        q_db += _is_tri_db_call(rec["arguments"])
        per_q_db.append(q_db)
    return _record(
        leg,
        questions=len(files),
        pass_count=leg.pass_count_override,
        iterations=iterations,
        raw=raw,
        prompt=prompt,
        cached=cached,
        completion=completion,
        db=sum(per_q_db),
        per_q_db=per_q_db,
    )


def _record(
    leg: Leg,
    *,
    questions: int,
    pass_count: int | None,
    iterations: int,
    raw: int,
    prompt: int,
    cached: int,
    completion: int,
    db: int,
    per_q_db: list[int],
) -> dict:
    notes = leg.notes
    adj: float | None = round(adjusted(prompt, cached, completion))
    if cached == 0:
        # Pre-2026-08-12 runs have no measured cache fields; adjusted would
        # silently equal raw and poison cross-leg comparisons.
        adj = None
        notes = (
            f"{notes} Run predates measured cache fields; cache-adjusted "
            "tokens not comparable (would equal raw)."
        ).strip()
    return {
        "leg": leg.label,
        "run_dir": leg.run_dir,
        "regime": leg.regime,
        "warehouse_tables": leg.warehouse_tables,
        "questions": questions,
        "pass_count": pass_count,
        "iterations": iterations,
        "raw_tokens": raw,
        "cached_prompt_tokens": cached,
        "cache_adjusted_tokens": adj,
        "db_queries": db,
        "db_queries_per_question": round(db / questions, 2) if questions else None,
        "db_queries_per_question_list": per_q_db,
        "notes": notes,
    }


def build_dataset(
    results_dir: Path = RESULTS_DIR, legs: tuple[Leg, ...] = LEGS
) -> dict:
    records = []
    for leg in legs:
        if (results_dir / leg.run_dir / "report.json").exists():
            records.append(leg_from_report(leg, results_dir))
        elif glob.glob(str(results_dir / leg.run_dir / "agent_log.q*.jsonl")):
            records.append(leg_from_jsonl(leg, results_dir))
        else:
            raise FileNotFoundError(f"{leg.run_dir}: no report.json or agent logs")
    return {
        "source": "pytrilogy evals/tpcds_agent; legs declared in export_pareto_data.py",
        "model": "deepseek-v4-flash",
        "scale_factor": 1,
        "questions_per_leg": 20,
        "metric_definitions": {
            "regime": "bare_discovery = no schema.md, agent introspects the DB "
            "itself; schema_injection = full schema.md handed to the agent; "
            "enriched_trilogy = curated Trilogy semantic model, no raw DB "
            "access encouraged",
            "warehouse_tables": "total tables in the warehouse (24 real + noise "
            "at dose)",
            "raw_tokens": "sum of total_tokens over all turns, all questions",
            "cache_adjusted_tokens": "(prompt - cached) + 0.1*cached + "
            "completion; cache-hit input weighted at 0.1 per DeepSeek "
            "published pricing ratio",
            "db_queries": "tool calls that execute against the database: "
            "run_query+run_file for SQL legs, `trilogy run` (and `file write "
            "--run`) for enriched legs — explore/agent-info/file read the "
            "semantic model, not the DB",
            "pass_count": "reference-checked correct answers out of questions",
        },
        "caveats": [
            (
                "SF=1 DuckDB: probes cost milliseconds locally; the probe axis "
                "matters economically on cloud warehouses (per-query latency "
                "floors, per-scan billing), not here."
            ),
            (
                "Enriched accuracy swung 16<->20 across byte-identical "
                "replicates; per-cell accuracy deltas under ~4 passes are "
                "noise at n=20."
            ),
            (
                "Probe weight is asymmetric: bare-discovery probes skew to "
                "cheap information_schema pagination; each enriched run "
                "carries ~1.6s p50 client-side compile."
            ),
            (
                "Enriched legs are dose-independent by construction (agent "
                "never sees the noisy schema); plot as a horizontal reference "
                "against dose sweeps."
            ),
            (
                "Confusable legs from run 20260812-153111 are the v1 treatment "
                "(trap tables undocumented — a since-closed information "
                "bleed); do not compare v2 confusable runs against them "
                "cell-to-cell."
            ),
        ],
        "legs": records,
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "-o",
        "--output",
        default=str(Path(__file__).resolve().parent / "charts" / "pareto_data.json"),
        help="output JSON path (pass the blog's pit_of_success_pareto_data.json "
        "path to refresh the published dataset)",
    )
    parser.add_argument(
        "--results-dir",
        default=str(RESULTS_DIR),
        help="results directory holding the run folders",
    )
    args = parser.parse_args()
    dataset = build_dataset(Path(args.results_dir))
    out = Path(args.output)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(dataset, indent=1), encoding="utf-8")
    for leg in dataset["legs"]:
        adj = leg["cache_adjusted_tokens"]
        print(
            f"{leg['leg']:<28}{leg['questions']:>3}q pass={leg['pass_count']!s:>4} "
            f"raw={leg['raw_tokens'] / 1e6:.2f}M "
            f"adj={'n/a' if adj is None else f'{adj / 1e6:.2f}M':>6} "
            f"db={leg['db_queries']} ({leg['db_queries_per_question']}/q)"
        )
    print(f"wrote {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
