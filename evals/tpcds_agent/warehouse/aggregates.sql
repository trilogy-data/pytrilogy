CREATE OR REPLACE TABLE agg_store_sales_daily AS
SELECT
    ss_sold_date_sk,
    ss_item_sk,
    ss_customer_sk,
    ss_cdemo_sk,
    ss_hdemo_sk,
    ss_store_sk,
    ss_promo_sk,
    ss_addr_sk,
    count(*) AS count_rows,
    count(ss_item_sk) AS count_items,
    count(ss_customer_sk) AS count_customers,
    count(ss_ticket_number) AS count_tickets,
    sum(ss_quantity) AS sum_quantity,
    sum(ss_sales_price) AS sum_sales_price,
    sum(ss_list_price) AS sum_list_price,
    sum(ss_ext_sales_price) AS sum_ext_sales_price,
    sum(ss_ext_list_price) AS sum_ext_list_price,
    sum(ss_ext_wholesale_cost) AS sum_ext_wholesale_cost,
    sum(ss_ext_discount_amt) AS sum_ext_discount_amt,
    sum(ss_net_profit) AS sum_net_profit,
    sum(ss_coupon_amt) AS sum_coupon_amt,
    sum(ss_net_paid) AS sum_net_paid,
    sum(ss_ext_tax) AS sum_ext_tax,
    sum(ss_wholesale_cost) AS sum_wholesale_cost
FROM store_sales
GROUP BY ALL;

