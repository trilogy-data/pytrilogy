_Declared = tuple[Purpose, Derivation, frozenset[str]]

# derivations that GENERATE their key's values, so the concept is that key's
# whole domain rather than a function or a subset of some source's rows
_DOMAIN_GENERATORS = frozenset({Derivation.UNNEST, Derivation.CONSTANT})

# key -> the `~` bindings between a source's rows and that key's whole domain
Carried = dict[str, frozenset[str]]


@dataclass(frozen=True)
class _SourceFacts:
    identifier: str
    grain: frozenset[str]
    grain_is_partial: bool
    # bound address -> ({address} when bound `~`, else empty)
    bound: Carried
    # every address a row has a value for by keyed lookup, with its cause
    # (`_carried`); stamped once every source of the model is known
    carried: Carried = field(default_factory=dict)


@dataclass
class ModelFacts:
    """Binding facts of one scope, canonicalized over pseudonyms."""

    canonical: dict[str, str]
    sources: tuple[_SourceFacts, ...]
    # every spelling of an address that is part of some source's row identity
    identifying: frozenset[str] = frozenset()
    reach: dict[frozenset[str], frozenset[str]] = field(default_factory=dict)

    def lookup_supply(
        self, identifier: str, without: str | None = None
    ) -> frozenset[str]:
        """What a row of source `identifier` has a value for by keyed lookup,
        with the `without` source left out of the model. The FD closure is the
        wrong tool for this: a same-grain sibling binding its keys `~` is in
        the closure yet may hold no row for the key. The lookup over-
        approximates (a nullable FK may miss), the safe direction for the
        pin-heal: a killer counted as suppliable only blocks healing."""
        source = next(s for s in self.sources if s.identifier == identifier)
        if without is None:
            return frozenset(source.carried)
        rest = tuple(s for s in self.sources if s.identifier != without)
        return frozenset(_carried(source, rest))

    def component_of(self, identifier: str) -> frozenset[str]:
        """Every address bound by a source connected to `identifier` through
        shared bindings: its model component."""
        bound = [source.bound.keys() for source in self.sources]
        index = next(
            i for i, s in enumerate(self.sources) if s.identifier == identifier
        )
        component = next(c for c in overlap_components(bound) if index in c)
        return frozenset().union(*(bound[i] for i in component))

    def reach_of(self, keys: frozenset[str]) -> frozenset[str]:
        """Addresses a keyed lookup arrives at from `keys` together: a
        composite-key dimension (`grain (name, variant)`) is entered only
        with its whole grain, so no span alone reaches its properties."""
        cached = self.reach.get(keys)
        if cached is None:
            seed = _SourceFacts("", frozenset(), False, {k: frozenset() for k in keys})
            cached = self.reach[keys] = frozenset(_carried(seed, self.sources))
        return cached


@dataclass(frozen=True)
class RowsetRegion:
    """One live region of a rowset body, in the handles that expose it:
    `present` the key handles on it, `bound` every handle defined on it,
    `spans` the handles spelling the body region's spans (`body_spans`)."""

    present: frozenset[str]
    bound: frozenset[str]
    spans: frozenset[str]
    body_spans: frozenset[str]


@dataclass(frozen=True)
class RowsetWitness:
    """A rowset the plan reads, as a source of it (`rowset_witness`)."""

    name: str
    regions: tuple[RowsetRegion, ...]
    # handle -> the key handles it is a function of, within this rowset
    entity_handles: dict[str, frozenset[str]] = field(default_factory=dict)
    # every spelling a join inside the body pads one of its spans under (the
    # body's own, and those of the rowsets it reads) -> the handle spelling it
    spellings: dict[str, str] = field(default_factory=dict)

    @property
    def licensed(self) -> bool:
        return any(r.spans for r in self.regions)

    def regions_within(self, spans: frozenset[str]) -> list[RowsetRegion]:
        """The extension regions `spans` covers."""
        return [r for r in self.regions if r.spans and r.spans <= spans]

    def body_spans_of(self, spans: frozenset[str]) -> frozenset[str]:
        """The body's spelling of every region `spans` covers."""
        return frozenset().union(*(r.body_spans for r in self.regions_within(spans)))


def rowset_witness(
    name: str,
    handles: list[BuildConcept],
    body: Keyspace,
    body_environment: BuildEnvironment,
    body_scope: ScopeDatasources,
) -> RowsetWitness:
    """The body's live regions respelled in the rowset's handles. A body key
    no handle spells is spelled by a handle keyed on it alone (`item_desc`
    for the item the rowset exposes no key of): the reader identifies those
    rows by what they carry, as a property identifying a source is an entity
    (`_row_identities`). A region whose span nothing spells is one the reader
    cannot name, so it is not a region of the reader's plan (its rows are
    read as the base region's)."""
    canonical = scope_facts(body_scope, body_environment).canonical
    # the body keys what it DECLARED (`local._t_st`, the pinned alias); its
    # canonical spelling may be another pseudonym of the same value that the
    # body never read (an earlier rowset's `local._a_st`, keyed on the order)
    declared = {
        h.address: h.lineage.content.address
        for h in handles
        if isinstance(h.lineage, BuildRowsetItem)
    }
    contents = {h: canonical.get(a, a) for h, a in declared.items()}
    keys = {
        handle: body.keys_by_address.get(address)
        or frozenset(
            canonical.get(k, k)
            for k in entity_keys(address, body_environment, body_scope)
        )
        for handle, address in declared.items()
    }
    handles_of: dict[str, frozenset[str]] = {
        c: frozenset(h for h, hc in contents.items() if hc == c)
        for c in contents.values()
    }
    # a value-nullable stand-in (`item_desc string?`) pairs its NULL member
    # with a NULL-keyed guest's row and vetoes the join into a FULL, so a
    # handle that cannot be NULL spells the key first
    nullable = {
        h.address
        for h in handles
        if isinstance(h.lineage, BuildRowsetItem) and h.lineage.content.is_nullable
    }
    for key in sorted(frozenset().union(*keys.values()) - handles_of.keys()):
        carriers = sorted(
            (h for h, k in keys.items() if k == {key}), key=lambda h: (h in nullable, h)
        )
        if carriers:
            handles_of[key] = frozenset(carriers[:1])
    entity_handles = {
        handle: frozenset().union(
            *(handles_of.get(k, frozenset()) for k in keys[handle])
        )
        for handle in contents
    }
    # the body pads for a span under its own spelling and, for a rowset it
    # reads in turn, under that body's; the reader names all of them by the
    # handle. A span nothing spells stays unnamed here.
    spellings: dict[str, str] = {}
    for span in body.in_play_spans:
        spelled_by = handles_of.get(canonical.get(span, span))
        if not spelled_by:
            continue
        handle = min(spelled_by)
        spellings[span] = spellings[canonical.get(span, span)] = handle
        spellings.update(
            (below, handle)
            for below, spelled in body.witnessed.items()
            if canonical.get(spelled, spelled) == canonical.get(span, span)
        )
    regions: list[RowsetRegion] = []
    for region in body.live_regions:
        body_spans = {canonical.get(s, s) for s in region.spans}
        if not body_spans <= handles_of.keys():
            continue
        regions.append(
            RowsetRegion(
                present=frozenset().union(
                    *(handles_of.get(k, frozenset()) for k in region.present)
                ),
                bound=frozenset(h for h, k in keys.items() if k <= region.present),
                spans=frozenset().union(*(handles_of[s] for s in body_spans)),
                body_spans=region.spans,
            )
        )
    return RowsetWitness(
        name=name,
        regions=tuple(regions),
        entity_handles=entity_handles,
        spellings=spellings,
    )


def _rowset_sources(witnesses: tuple[RowsetWitness, ...]) -> tuple[_SourceFacts, ...]:
    """One source per witnessed region. A handle is bound `~` when a smaller
    region of the same body spells its key as a span: the larger rows reach
    the smaller region's rows through it, as `sales` reaches the items no sale
    references through `~item_sk`."""
    out: list[_SourceFacts] = []
    for witness in witnesses:
        for region in witness.regions:
            smaller_spans = frozenset().union(
                *(r.spans for r in witness.regions if r.present < region.present)
            )
            bound: Carried = {
                handle: witness.entity_handles.get(handle, frozenset()) & smaller_spans
                for handle in region.bound
            }
            out.append(
                _SourceFacts(
                    identifier=f"rowset:{witness.name}:{'|'.join(sorted(region.present))}",
                    grain=region.present,
                    grain_is_partial=any(bound.get(g) for g in region.present),
                    bound=bound,
                )
            )
    return tuple(out)


# per scope, for the life of its graph; see `ScopeDatasources`
_FACTS_CACHE: WeakKeyDictionary[ScopeDatasources, ModelFacts] = WeakKeyDictionary()


def scope_facts(scope: ScopeDatasources, environment: BuildEnvironment) -> ModelFacts:
    """The binding facts of one scope, computed on first read."""
    facts = _FACTS_CACHE.get(scope)
    if facts is None:
        facts = _FACTS_CACHE[scope] = _compute_facts(environment, scope.datasources)
    return facts


def _canonical_addresses(environment: BuildEnvironment) -> dict[str, str]:
    """address -> the smallest spelling among it and its pseudonyms."""
    classes: dict[str, set[str]] = {}
    for key, concept in environment.concepts.items():
        merged = {key, concept.address, *concept.pseudonyms}
        for member in list(merged):
            merged |= classes.get(member, set())
        for member in merged:
            classes[member] = merged
    return {address: min(members) for address, members in classes.items()}


def _better(new: frozenset[str], old: frozenset[str] | None) -> bool:
    return old is None or len(new) < len(old)


def _row_identities(
    environment: BuildEnvironment, datasources: Sequence[BuildDatasource]
) -> dict[str, frozenset[str]]:
    """What identifies a row of each source: its declared grain, else every
    KEY column it binds, less those the others determine by FD. A key that
    identifies another source on its own is NOT dropped for that alone: it is
    a foreign key on `customers (id, nation.id)` but half the grain of
    `lines (order_id, line_no, product_id)`, and reading the latter as one row
    per `line_no` let a return reach every order's first line."""
    return {
        ds.identifier: (
            frozenset(ds.grain.components)
            if not ds.grain.abstract
            else minimize_build_grain(
                environment,
                [
                    c.concept.address
                    for c in ds.columns
                    if c.concept.purpose == Purpose.KEY
                ],
            )
        )
        for ds in datasources
    }


def _source_facts(
    ds: BuildDatasource, canonical: dict[str, str], identity: frozenset[str]
) -> _SourceFacts:
    bound: Carried = {}
    for column in ds.columns:
        address = column.concept.address
        key = canonical.get(address, address)
        cause = ds.partial_spellings(column)
        if _better(cause, bound.get(key)):
            bound[key] = cause
    grain = frozenset(canonical.get(g, g) for g in identity)
    return _SourceFacts(
        identifier=ds.identifier,
        grain=grain,
        grain_is_partial=any(bound.get(g) for g in grain),
        bound=bound,
    )


def _generated_domains(
    environment: BuildEnvironment,
    canonical: dict[str, str],
    bound: tuple[_SourceFacts, ...],
) -> tuple[_SourceFacts, ...]:
    """A key some source binds `~` whose complete side is a derivation, not a
    table: `merge orid into ~orid_2` with `orid_2 <- unnest([1, 2, 3])`."""
    partial_keys = {key for s in bound for key, cause in s.bound.items() if cause}
    out: dict[str, _SourceFacts] = {}
    for concept in environment.concepts.values():
        key = canonical.get(concept.address, concept.address)
        if (
            concept.purpose == Purpose.KEY
            and concept.derivation in _DOMAIN_GENERATORS
            and key in partial_keys
        ):
            out[concept.address] = _SourceFacts(
                identifier=f"generated:{concept.address}",
                grain=frozenset({key}),
                grain_is_partial=False,
                bound={key: frozenset()},
            )
    return tuple(out[address] for address in sorted(out))


def _carried(anchor: _SourceFacts, sources: tuple[_SourceFacts, ...]) -> Carried:
    """Every address a row of `anchor` has a value for, by keyed lookup.

    A lookup enters a source only through its whole grain, and never one whose
    grain is bound `~`: that source may hold no row for the anchor's key.
    A source is re-entered only once a grain address it reads has improved:
    re-entering on the same paths improves nothing."""
    carried = dict(anchor.bound)
    # tick of each address's last improvement; a source's last entry tick
    changed_at = dict.fromkeys(carried, 0)
    entered_at: dict[int, int] = {}
    tick = 0
    changed = True
    while changed:
        changed = False
        for i, other in enumerate(sources):
            if other is anchor or not other.grain or other.grain_is_partial:
                continue
            if not other.grain <= carried.keys():
                continue
            last = entered_at.get(i)
            if last is not None and all(changed_at[g] < last for g in other.grain):
                continue
            tick += 1
            entered_at[i] = tick
            path: frozenset[str] = frozenset().union(*(carried[g] for g in other.grain))
            for address, cause in other.bound.items():
                if _better(path | cause, carried.get(address)):
                    carried[address] = path | cause
                    changed_at[address] = tick
                    changed = True
    return carried


def _respelled(source: _SourceFacts, canonical: dict[str, str]) -> _SourceFacts:
    """A rowset's facts are spelled in its handles; the plan reading it keys
    its entities canonically, and a body reading `t.o as o2` makes the alias
    the canonical spelling. The `~` cause keeps the handle it was spelled on,
    as a datasource's keeps the address it was authored on."""
    bound: Carried = {}
    for address, cause in source.bound.items():
        key = canonical.get(address, address)
        if _better(cause, bound.get(key)):
            bound[key] = cause
    return dataclasses.replace(
        source,
        grain=frozenset(canonical.get(g, g) for g in source.grain),
        bound=bound,
    )


def _stamped(sources: tuple[_SourceFacts, ...]) -> tuple[_SourceFacts, ...]:
    return tuple(dataclasses.replace(s, carried=_carried(s, sources)) for s in sources)


def _identifying(
    canonical: dict[str, str], sources: tuple[_SourceFacts, ...]
) -> frozenset[str]:
    grains: frozenset[str] = frozenset().union(*(s.grain for s in sources))
    return frozenset(address for address, key in canonical.items() if key in grains)


def _compute_facts(
    environment: BuildEnvironment, datasources: Sequence[BuildDatasource]
) -> ModelFacts:
    canonical = _canonical_addresses(environment)
    identities = _row_identities(environment, datasources)
    bound = tuple(
        _source_facts(ds, canonical, identities[ds.identifier]) for ds in datasources
    )
    sources = _stamped(bound + _generated_domains(environment, canonical, bound))
    return ModelFacts(
        canonical=canonical,
        sources=sources,
        identifying=_identifying(canonical, sources),
    )


def _with_rowsets(facts: ModelFacts, rowsets: tuple[_SourceFacts, ...]) -> ModelFacts:
    """`facts` beside the rowsets a plan reads: only `carried` changes for the
    model's own sources."""
    respelled = tuple(_respelled(r, facts.canonical) for r in rowsets)
    return ModelFacts(
        canonical=facts.canonical,
        sources=_stamped(facts.sources + respelled),
        identifying=facts.identifying | _identifying(facts.canonical, respelled),
    )


def _entity_keys(
    address: str,
    declared: dict[str, _Declared],
    identifying: frozenset[str],
    environment: BuildEnvironment,
    seen: frozenset[str] = frozenset(),
) -> frozenset[str]:
    """The entity keys a concept is a function of. A key is its own entity:
    the `keys` it carries are an FK-path addressing artifact (`customer_id`
    bound on `orders` lists `order_id`), not a determinant. So is a property
    that identifies the rows of some source (`region`, the grain of
    `region_dim`). Anything else lives on its keys' entities: an aggregate `by
    status` is keyed on the order. A BASIC is a function of what it READS
    (`orbit_code <- upper(category)`), not of its declared keys: over an
    aggregate those still name the aggregate's argument (`coalesce(sum(amount),
    0)` lists `order_id`), which the aggregate is evaluated OVER, not on.

    A rowset key stays its OWN entity: the rowset is a row source, and stores
    no order references are not rows of `select even_orders.store_id`."""
    known = declared.get(address)
    if known is None:
        concept = environment.concepts.get(address)
        if concept is None:
            return frozenset()
        known = (concept.purpose, concept.derivation, frozenset(concept.keys or ()))
    purpose, derivation, keys = known
    own_entity = purpose == Purpose.KEY and derivation != Derivation.BASIC
    if own_entity or address in identifying:
        return frozenset({address})
    if derivation == Derivation.BASIC:
        # a select-row expression is keyed on the anchors it was pinned to
        keys = (
            _grain_pin_addresses(address, environment)
            or lineage_reads(address, environment)
            or keys
        )
    elif derivation == Derivation.AGGREGATE and not keys:
        # a ROLLUP aggregate declares no keys; it is still evaluated by its `by`
        keys = _grouping_addresses(address, environment)
    elif derivation == Derivation.GROUP_TO:
        # `group(status) by customer_id` pairs the customer's domain with the
        # statuses it has: a row of the customer, NULL-valued where it has none
        keys = _group_to_addresses(address, environment) or keys
    seen = seen | {address}
    return frozenset().union(
        *(
            _entity_keys(k, declared, identifying, environment, seen)
            for k in keys
            if k not in seen
        )
    )


def entity_keys(
    address: str, environment: BuildEnvironment, scope: ScopeDatasources
) -> frozenset[str]:
    """The entity keys `address` is a function of (`_entity_keys`)."""
    identifying = scope_facts(scope, environment).identifying
    return _entity_keys(address, {}, identifying, environment)


def lineage_reads(address: str, environment: BuildEnvironment) -> frozenset[str]:
    """The addresses the lineage of `address` reads directly."""
    concept = environment.concepts.get(address)
    if concept is None or concept.lineage is None:
        return frozenset()
    return frozenset(arg.address for arg in concept.lineage.concept_arguments)


def _group_to_addresses(address: str, environment: BuildEnvironment) -> frozenset[str]:
    concept = environment.concepts.get(address)
    if concept is None or not isinstance(concept.lineage, BuildFunction):
        return frozenset()
    return frozenset(
        arg.address
        for arg in concept.lineage.arguments[1:]
        if isinstance(arg, BuildConcept)
    )


def _grain_pin_addresses(address: str, environment: BuildEnvironment) -> frozenset[str]:
    concept = environment.concepts.get(address)
    if (
        concept is None
        or not isinstance(concept.lineage, BuildFunction)
        or concept.lineage.operator != FunctionType.GRAIN_PIN
    ):
        return frozenset()
    return _group_to_addresses(address, environment)


def _grouping_addresses(address: str, environment: BuildEnvironment) -> frozenset[str]:
    concept = environment.concepts.get(address)
    if concept is None or not isinstance(concept.lineage, BuildAggregateWrapper):
        return frozenset()
    return frozenset(b.address for b in concept.lineage.by)


def _identifying_keys(source: _SourceFacts, present: frozenset[str]) -> frozenset[str]:
    """What identifies `source`'s rows once projected onto `present`: its grain
    when the projection keeps it, else every projected key."""
    if source.grain and source.grain <= present:
        return source.grain
    return present


def _witnesses(
    entities: frozenset[str], facts: ModelFacts
) -> dict[frozenset[str], list[_SourceFacts]]:
    """present -> the sources whose rows carry exactly those entities."""
    out: dict[frozenset[str], list[_SourceFacts]] = {}
    for source in facts.sources:
        present = frozenset(source.carried.keys() & entities)
        if present:
            out.setdefault(present, []).append(source)
    return out


def _identity_cause(source: _SourceFacts, identity: frozenset[str]) -> frozenset[str]:
    return frozenset().union(*(source.carried[k] for k in identity))


def _extension_spans(
    present: frozenset[str],
    witness: _SourceFacts,
    witnesses: dict[frozenset[str], list[_SourceFacts]],
) -> frozenset[str]:
    """The `~` keys that keep `witness`'s rows out of every larger region;
    empty when it holds only some of its own, or a larger source holds them all."""
    identity = _identifying_keys(witness, present)
    if _identity_cause(witness, identity):
        return frozenset()
    blocking = [
        _identity_cause(larger, identity)
        for cell, sources in witnesses.items()
        if cell > present
        for larger in sources
    ]
    if not blocking or not all(blocking):
        return frozenset()
    return frozenset().union(*blocking)


def _bridges(
    source: _SourceFacts,
    present: frozenset[str],
    entities: frozenset[str],
    facts: ModelFacts,
) -> bool:
    """`source` shares a column with a source carrying an entity outside
    `present`: the fan-out join that relates this region to the rest of the
    statement (`stages` between `engines` and the launches)."""
    return any(
        other is not source
        and source.bound.keys() & other.bound.keys()
        and (other.carried.keys() & entities) - present
        for other in facts.sources
    )


def _completions(
    present: frozenset[str],
    sources: list[_SourceFacts],
    requested_roots: frozenset[str],
    entities: frozenset[str],
    rejected: frozenset[str],
    facts: ModelFacts,
) -> tuple[Completion, ...]:
    """The sources the plan needs that hold only some of this region's rows,
    beside a source holding all of them: `returns` beside `lines`. Needed
    means it alone binds something requested, or it is what joins the region
    to the rest of the statement."""
    causes = {
        s.identifier: _identity_cause(s, _identifying_keys(s, present)) for s in sources
    }
    complete = [s for s in sources if not causes[s.identifier]]
    if not complete:
        # two partial sources have no defined relationship: the full set is a
        # complete source (or a `complete where` slice the union machinery
        # stacks), never the partial ones completing each other
        return ()
    held: frozenset[str] = frozenset().union(*(s.carried.keys() for s in complete))
    return tuple(
        Completion(
            source=s.identifier,
            spans=causes[s.identifier],
            # NULL on every row of the region this source has no match for
            emptied_by=rejected & (s.carried.keys() - held),
        )
        for s in sources
        if causes[s.identifier]
        and (
            (s.bound.keys() & requested_roots) - held
            or _bridges(s, present, entities, facts)
        )
    )


def _connected(
    entities: frozenset[str], facts: ModelFacts
) -> dict[str, frozenset[str]]:
    """entity -> the entities of its model component: sources sharing a column
    can be joined, so their entities meet on some row."""
    columns = [source.carried.keys() for source in facts.sources]
    out = {e: frozenset({e}) for e in entities}
    for component in overlap_components(columns):
        found = entities & frozenset().union(*(columns[i] for i in component))
        for entity in found:
            out[entity] = found
    return out


def _region_order(item: tuple[frozenset[str], object]) -> list[str]:
    return sorted(item[0])


def null_rejected(conditions: list[BuildWhereClause]) -> set[str]:
    """What the statement's WHERE forces non-null, BETWEEN included: an absent
    concept is NULL however it renders, so every atom that rejects NULL empties
    the region it is absent on."""
    out: set[str] = set()
    for clause in conditions:
        out |= gather_non_null_proofs(clause.conditional)
    return out


def _has_extension_license(datasources: Sequence[BuildDatasource]) -> bool:
    return any(ds.column_level_partial_addresses for ds in datasources)


def _entity_reach(
    facts: ModelFacts,
    canonical: dict[str, str],
    entities: frozenset[str],
    spans: frozenset[str],
) -> frozenset[str]:
    return facts.reach_of(frozenset(canonical.get(s, s) for s in spans)) & entities


def build_keyspace(
    concept_attrs: dict[str, ConceptAttrs],
    mandatory_list: list[BuildConcept],
    environment: BuildEnvironment,
    conditions: list[BuildWhereClause],
    scope: ScopeDatasources,
    rowset_witnesses: tuple[RowsetWitness, ...] = (),
) -> Keyspace:
    """`scope` is the bindings the plan is built over (its graph's), or the
    bindings as authored for the heal that decides them. `rowset_witnesses`
    are the rowsets the plan reads, sources beside them.

    The facts are read whether or not any `~` survives (pin-heal may have
    dropped the last one): an entity is spelled by the same canonical
    address either way, and a plan's keys are compared across plans."""
    facts = scope_facts(scope, environment)
    rowsets = _rowset_sources(rowset_witnesses)
    if rowsets:
        facts = _with_rowsets(facts, rowsets)
    licensed = _has_extension_license(scope.datasources) or any(
        w.licensed for w in rowset_witnesses
    )
    witnessed = {s: h for w in rowset_witnesses for s, h in w.spellings.items()}
    canonical = facts.canonical
    identifying = facts.identifying
    # an existence-only node is a semijoin's subselect, not a row of this plan.
    # A rowset handle declares no keys; its entity is the handle the witness
    # spells its key by (`s.n` lives on `s.d`, the stand-in for the item).
    handle_keys = {
        handle: keys
        for witness in rowset_witnesses
        for handle, keys in witness.entity_handles.items()
    }
    declared = {
        a.address: (a.purpose, a.derivation, handle_keys.get(a.address, a.keys))
        for a in concept_attrs.values()
        if not a.existence_only and not a.relation_only
    }
    keys_by_address = {
        address: frozenset(
            canonical.get(k, k)
            for k in _entity_keys(address, declared, identifying, environment)
        )
        for address in declared
    }
    entities: frozenset[str] = frozenset().union(*keys_by_address.values())
    # a body region no requested entity is present on: every handle read is
    # absent on its rows, so they are not rows of this plan, whatever the
    # body extended them for (`select s.o, s.st` over a body naming the
    # customer; a product region under `select s.u, count(s.i)`)
    unread: frozenset[str] = frozenset().union(
        *(
            r.spans
            for w in rowset_witnesses
            for r in w.regions
            if r.spans and not {canonical.get(p, p) for p in r.present} & entities
        )
    )
    if not licensed or not entities:
        return Keyspace(
            regions=(Region(present=entities),),
            keys_by_address=keys_by_address,
            witnessed=witnessed,
            unread_spans=unread,
        )
    requested_roots = frozenset(
        canonical.get(a.address, a.address)
        for a in concept_attrs.values()
        if a.derivation == Derivation.ROOT
    )
    witnesses = _witnesses(entities, facts)
    connected = _connected(entities, facts)
    rejected = null_rejected(conditions)
    rejected_roots = frozenset(canonical.get(a, a) for a in rejected)

    base_sources = witnesses.get(entities, [])
    regions = [
        Region(
            present=entities,
            witnesses=frozenset(s.identifier for s in base_sources),
            completions=_completions(
                entities, base_sources, requested_roots, entities, rejected_roots, facts
            ),
        )
    ]
    for present, sources in sorted(witnesses.items(), key=_region_order):
        if present == entities:
            continue
        spans_by_witness = {
            s.identifier: _extension_spans(present, s, witnesses) for s in sources
        }
        completions = _completions(
            present, sources, requested_roots, entities, rejected_roots, facts
        )
        # kept out of the larger regions by a lookup's `~`, or by a bridge's
        spans: frozenset[str] = frozenset().union(
            *(c.spans for c in completions), *spans_by_witness.values()
        )
        if not spans:
            continue
        # an entity no source relates to this region's rows is cross-joined
        # onto every row, so it is present here too
        related: frozenset[str] = frozenset().union(*(connected[e] for e in present))
        full = present | (entities - related)
        reach = _entity_reach(facts, canonical, entities, spans)
        regions.append(
            Region(
                present=full,
                spans=spans,
                has_own_rows=any(spans_by_witness.values()),
                witnesses=frozenset(s.identifier for s in sources),
                completions=completions,
                emptied_by=frozenset(
                    a
                    for a in rejected
                    if not keys_by_address.get(a, frozenset()) <= full
                    and not _counts_the_rows(
                        a, reach, declared, identifying, canonical, environment
                    )
                ),
                reach=reach,
                filtered=any(
                    not (keys := keys_by_address.get(c.address)) or not keys <= reach
                    for clause in conditions
                    for c in clause.row_arguments
                ),
            )
        )
    return Keyspace(
        regions=tuple(regions),
        keys_by_address=keys_by_address,
        outputs=tuple(c.address for c in mandatory_list),
        span_reach={
            span: _entity_reach(facts, canonical, entities, frozenset({span}))
            for span in spans_in_play(regions)
        },
        witnessed=witnessed,
        unread_spans=unread,
        value_null_spans=_value_null_spans(scope.datasources, canonical)
        & spans_in_play(regions),
    )


def _counts_the_rows(
    address: str,
    reach: frozenset[str],
    declared: dict[str, _Declared],
    identifying: frozenset[str],
    canonical: dict[str, str],
    environment: BuildEnvironment,
) -> bool:
    """An aggregate evaluated over the region's rows takes a value there
    whatever its `by`: a WHERE rejecting its NULL leaves those rows in."""
    return arguments_within(
        environment.concepts.get(address),
        lambda a: frozenset(
            canonical.get(k, k)
            for k in _entity_keys(a, declared, identifying, environment)
        ),
        reach,
    )


def _value_null_spans(
    datasources: Sequence[BuildDatasource], canonical: dict[str, str]
) -> frozenset[str]:
    return frozenset(
        canonical.get(c.address, c.address)
        for ds in datasources
        for c in ds.nullable_concepts
    )
